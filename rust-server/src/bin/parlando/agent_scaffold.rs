//! Generates a standalone Rust policy and regenerates its game wire types.

use super::{project::ScaffoldSdk, Language};
use anyhow::{ensure, Context, Result};
use parlando_game_sdk::{EnumRepresentation, Field, GameSchema, Schema, Variant, VariantPayload};
use std::{
    collections::HashSet,
    fmt::Write as _,
    fs,
    io::{ErrorKind, Write as _},
    path::Path,
};

const GENERATED: &str = "// @generated by parlando. Regenerate this file from the game schema.";
const CARGO: &str = include_str!("../../../templates/agent/Cargo.toml.template");
const POLICY: &str = include_str!("../../../templates/agent/lib.rs");

/// Selects the Beacon example from its public contract, including starter games with custom IDs.
fn supports_tick(schema: &GameSchema) -> bool {
    matches!(schema.action.as_ref(), Schema::Struct(fields) if matches!(fields.as_slice(), [field] if field.name == "ticks" && field.schema == Schema::U64))
        && matches!(schema.view_a.as_ref(), Schema::Struct(fields) if fields.iter().any(|field| field.name == "your_turn" && field.schema == Schema::Bool))
}

/// Writes the editable policy and Cargo files into the new project staging directory.
pub(super) fn scaffold(
    root: &Path,
    id: &str,
    name: &str,
    schema: &GameSchema,
    sdk: Option<&Path>,
) -> Result<()> {
    let dependency = ScaffoldSdk::select(&Language::Rust, sdk)?.install(&Language::Rust, root)?;
    let cargo = CARGO
        .replace("__PACKAGE_ID__", &id.replace('.', "-"))
        .replace("__SDK_DEPENDENCY__", &dependency);
    fs::create_dir(root.join("src"))?;
    fs::write(root.join("Cargo.toml"), cargo)?;
    let policy = if supports_tick(schema) {
        include_str!("../../../templates/agent/beacon.rs")
    } else {
        POLICY
    };
    fs::write(
        root.join("src/lib.rs"),
        policy
            .replace("__AGENT_ID__", id)
            .replace("__AGENT_NAME__", &format!("{name:?}")),
    )?;
    fs::write(root.join(".gitignore"), "/target/\n/dist/\n/.parlando/\n")?;
    Ok(())
}

/// Regenerates the owned binding module atomically while preserving the editable policy.
pub(super) fn bindings(destination: &Path, schema: &GameSchema) -> Result<()> {
    let source = render(schema);
    let folder = destination
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    let exists = match fs::read(destination) {
        Ok(existing) => {
            ensure!(
                existing.starts_with(GENERATED.as_bytes()),
                "{} does not have the Parlando generated-file header",
                destination.display()
            );
            if existing == source.as_bytes() {
                return Ok(());
            }
            true
        }
        Err(error) if error.kind() == ErrorKind::NotFound => {
            fs::create_dir_all(folder)?;
            false
        }
        Err(error) => return Err(error).context("reading existing game bindings"),
    };
    let mut file = tempfile::NamedTempFile::new_in(folder)?;
    file.write_all(source.as_bytes())?;
    let saved = if exists {
        file.persist(destination)
    } else {
        file.persist_noclobber(destination)
    };
    saved.with_context(|| format!("writing {}", destination.display()))?;
    Ok(())
}

/// Produces the policy's exported binding types in a stable order for the given game.
fn render(schema: &GameSchema) -> String {
    let mut generator = Generator {
        source: format!(
            "{GENERATED}\n//! Compact action, seat observations, and completion for this game.\n\n"
        ),
    };
    generator.root("Action", "An action accepted by the game.", &schema.action);
    generator.root(
        "ViewA",
        "The private observation for seat A.",
        &schema.view_a,
    );
    if schema.view_b == schema.view_a {
        generator.source.push_str(
            "/// The private observation for seat B uses the same layout as seat A.\n\
             pub type ViewB = ViewA;\n\n",
        );
    } else {
        generator.root(
            "ViewB",
            "The private observation for seat B.",
            &schema.view_b,
        );
    }
    generator.root(
        "Completion",
        "The shared result of a completed game.",
        &schema.completion,
    );
    generator.source
}

/// Accumulates Rust declarations in dependency order for a single game schema.
struct Generator {
    source: String,
}

impl Generator {
    /// Emits a public entry type, using an alias for primitives and containers.
    fn root(&mut self, name: &str, doc: &str, schema: &Schema) {
        let rust_type = self.ty(name, doc, schema);
        if rust_type != name {
            writeln!(self.source, "/// {doc}\npub type {name} = {rust_type};\n").unwrap();
        }
    }

    /// Converts a declared value to its Rust type, emitting compound dependencies first.
    fn ty(&mut self, name: &str, doc: &str, schema: &Schema) -> String {
        match schema {
            Schema::Dynamic => "serde_json::Value".into(),
            Schema::Null => "()".into(),
            Schema::Bool => "bool".into(),
            Schema::I64 => "i64".into(),
            Schema::U64 => "u64".into(),
            Schema::F64 => "f64".into(),
            Schema::String => "String".into(),
            Schema::Option(inner) => format!("Option<{}>", self.item(name, inner)),
            Schema::List(inner) => format!("Vec<{}>", self.item(name, inner)),
            Schema::Map(inner) => format!(
                "std::collections::BTreeMap<String, {}>",
                self.item(name, inner)
            ),
            Schema::Tuple(items) => {
                let types = self.positional(name, items);
                if let [ty] = types.as_slice() {
                    self.singleton_tuple(name, doc, ty);
                } else {
                    let fields = types
                        .iter()
                        .map(|ty| format!("pub {ty}"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    writeln!(self.source,
                        "/// {doc}\n#[derive(Clone, Debug, parlando_game_sdk::GameValue)]\npub struct {name}({fields});\n").unwrap();
                }
                name.into()
            }
            Schema::Struct(fields) => {
                let fields = self.named(name, fields);
                writeln!(self.source,
                    "/// {doc}\n#[derive(Clone, Debug, parlando_game_sdk::GameValue)]\npub struct {name} {{").unwrap();
                for field in fields {
                    field.write(&mut self.source, "    ", "pub ", true);
                }
                self.source.push_str("}\n\n");
                name.into()
            }
            Schema::Enum {
                representation,
                variants,
            } => {
                self.enumeration(name, doc, schema, representation, variants);
                name.into()
            }
        }
    }

    /// Assigns the wrapped item its own stable declaration name when required.
    fn item(&mut self, name: &str, schema: &Schema) -> String {
        self.ty(
            &format!("{name}Item"),
            "An item in the containing game value.",
            schema,
        )
    }

    /// Resolves ordered positional types, retaining every compact slot.
    fn positional(&mut self, parent: &str, items: &[Schema]) -> Vec<String> {
        items
            .iter()
            .enumerate()
            .map(|(index, schema)| {
                self.ty(
                    &format!("{parent}Slot{}", index + 1),
                    "A positional game value.",
                    schema,
                )
            })
            .collect()
    }

    /// Resolves named fields with stable Rust spellings and their original wire names.
    fn named<'a>(&mut self, parent: &str, fields: &'a [Field]) -> Vec<NamedField<'a>> {
        let mut identifiers = HashSet::new();
        fields
            .iter()
            .enumerate()
            .map(|(index, field)| {
                let identifier = unique_identifier(
                    &field.name,
                    &format!("field_{}", index + 1),
                    &mut identifiers,
                );
                let ty = self.ty(
                    &format!("{parent}Field{}", index + 1),
                    "The value of a game field.",
                    &field.schema,
                );
                NamedField {
                    field,
                    identifier,
                    ty,
                }
            })
            .collect()
    }

    /// Emits the single-slot tuple codec because a Rust one-field tuple struct derives as a newtype.
    fn singleton_tuple(&mut self, name: &str, doc: &str, ty: &str) {
        writeln!(self.source, r#"/// {doc}
#[derive(Clone, Debug)]
pub struct {name}(pub {ty});

impl parlando_game_sdk::GameValue for {name} {{
    /// Declares the one positional slot.
    fn schema() -> parlando_game_sdk::Schema {{
        parlando_game_sdk::Schema::Tuple(vec![<{ty} as parlando_game_sdk::GameValue>::schema()])
    }}

    /// Writes one compact array slot.
    fn encode_compact<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {{
        use serde::ser::SerializeTuple;
        let mut tuple = serializer.serialize_tuple(1)?;
        tuple.serialize_element(&parlando_game_sdk::Compact(&self.0))?;
        tuple.end()
    }}
}}

impl<'de> parlando_game_sdk::DecodeGameValue<'de> for {name} {{
    /// Reads the value from its one positional slot.
    fn read_compact(reader: &mut parlando_game_sdk::CompactReader<'de>) -> parlando_game_sdk::CompactDecodeResult<Self> {{
        parlando_game_sdk::CompactReader::check_slots(reader.array()?, 1)?;
        reader.nested(|reader| Ok(Self(reader.read()?)))
    }}
}}
"#).unwrap();
    }

    /// Emits typed variants in ordinal order with the same public tagging convention as the game.
    fn enumeration(
        &mut self,
        name: &str,
        doc: &str,
        schema: &Schema,
        representation: &EnumRepresentation,
        variants: &[Variant],
    ) {
        let mut identifiers = HashSet::new();
        let manual = variants.iter().any(
            |variant| matches!(&variant.payload, VariantPayload::Tuple(slots) if slots.len() == 1),
        );
        let variants = variants
            .iter()
            .enumerate()
            .map(|(index, variant)| {
                let public = &variant.name;
                let preferred = variant_identifier(public);
                let identifier = unique_identifier(
                    &preferred,
                    &format!("Variant{}", index + 1),
                    &mut identifiers,
                );
                let parent = format!("{name}Variant{}", index + 1);
                let payload = match &variant.payload {
                    VariantPayload::Unit => Payload::Unit,
                    VariantPayload::Newtype(schema) => {
                        Payload::Positional(vec![self.item(&parent, schema)])
                    }
                    VariantPayload::Tuple(items) => {
                        Payload::Positional(self.positional(&parent, items))
                    }
                    VariantPayload::Struct(fields) => Payload::Named(self.named(&parent, fields)),
                };
                RustVariant {
                    public,
                    identifier,
                    payload,
                }
            })
            .collect::<Vec<_>>();
        writeln!(self.source, "/// {doc}").unwrap();
        if manual {
            self.source.push_str("#[derive(Clone, Debug)]\n");
        } else {
            self.source
                .push_str("#[derive(Clone, Debug, parlando_game_sdk::GameValue)]\n");
            match representation {
                EnumRepresentation::External => (),
                EnumRepresentation::Internal { tag } => {
                    writeln!(self.source, "#[serde(tag = {tag:?})]").unwrap()
                }
                EnumRepresentation::Adjacent { tag, content } => {
                    writeln!(
                        self.source,
                        "#[serde(tag = {tag:?}, content = {content:?})]"
                    )
                    .unwrap();
                }
                EnumRepresentation::Untagged => unreachable!("validated game schema"),
            }
        }
        writeln!(self.source, "pub enum {name} {{").unwrap();
        for variant in &variants {
            variant.write(&mut self.source, !manual);
        }
        self.source.push_str("}\n\n");
        if manual {
            self.singleton_enum(name, schema, &variants);
        }
    }

    /// Implements an exact declaration when a one-slot tuple variant would derive as a newtype.
    fn singleton_enum(&mut self, name: &str, schema: &Schema, variants: &[RustVariant<'_>]) {
        let schema = serde_json::to_string(schema).expect("serializing a valid game schema");
        writeln!(
            self.source,
            r#"impl parlando_game_sdk::GameValue for {name} {{
    /// Declares the game enum and its original variant payload kinds.
    fn schema() -> parlando_game_sdk::Schema {{
        serde_json::from_str({schema:?}).expect("generated game schema")
    }}

    /// Writes the variant ordinal followed by its compact slots.
    fn encode_compact<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {{
        use serde::ser::SerializeTuple;
        match self {{"#
        )
        .unwrap();
        for (ordinal, variant) in variants.iter().enumerate() {
            let bindings = variant.payload.bindings();
            let slots = bindings.len() + 1;
            let pattern = variant.pattern(&bindings);
            writeln!(self.source, "            {pattern} => {{\n                let mut tuple = serializer.serialize_tuple({slots})?;\n                tuple.serialize_element(&{ordinal}_u32)?;").unwrap();
            for binding in bindings {
                writeln!(self.source, "                tuple.serialize_element(&parlando_game_sdk::Compact({binding}))?;").unwrap();
            }
            self.source
                .push_str("                tuple.end()\n            }\n");
        }
        writeln!(self.source, r#"        }}
    }}
}}

impl<'de> parlando_game_sdk::DecodeGameValue<'de> for {name} {{
    /// Reads the variant ordinal and consumes exactly its declared positional slots.
    fn read_compact(reader: &mut parlando_game_sdk::CompactReader<'de>) -> parlando_game_sdk::CompactDecodeResult<Self> {{
        let slots = reader.array()?;
        match reader.ordinal()? {{"#).unwrap();
        for (ordinal, variant) in variants.iter().enumerate() {
            let bindings = variant.payload.bindings();
            let slots = bindings.len() + 1;
            let values = vec!["reader.read()?".into(); bindings.len()];
            let expression = variant.pattern(&values);
            writeln!(self.source, "            {ordinal} => {{\n                parlando_game_sdk::CompactReader::check_slots(slots, {slots})?;").unwrap();
            if values.is_empty() {
                writeln!(self.source, "                Ok({expression})").unwrap();
            } else {
                writeln!(
                    self.source,
                    "                reader.nested(|reader| Ok({expression}))"
                )
                .unwrap();
            }
            self.source.push_str("            }\n");
        }
        self.source.push_str("            _ => parlando_game_sdk::CompactReader::invalid_ordinal(),\n        }\n    }\n}\n\n");
    }
}

/// Pairs the wire field with a legal Rust identifier and its generated type.
struct NamedField<'a> {
    field: &'a Field,
    identifier: String,
    ty: String,
}

impl NamedField<'_> {
    /// Writes a public record field or a named enum variant slot.
    fn write(&self, output: &mut String, indent: &str, visibility: &str, derived: bool) {
        let Self {
            field,
            identifier,
            ty,
        } = self;
        let name = &field.name;
        writeln!(
            output,
            "{indent}#[doc = {:?}]",
            format!("Game field {name:?}.")
        )
        .unwrap();
        if derived {
            let optional = if field.omit_none {
                ", skip_serializing_if = \"Option::is_none\""
            } else {
                ""
            };
            writeln!(output, "{indent}#[serde(rename = {name:?}{optional})]").unwrap();
        }
        writeln!(output, "{indent}{visibility}{identifier}: {ty},").unwrap();
    }
}

/// Retains the public tag and its chosen identifier for both declarations and codecs.
struct RustVariant<'a> {
    public: &'a str,
    identifier: String,
    payload: Payload<'a>,
}

/// Holds a variant's generated field types in compact wire order.
enum Payload<'a> {
    Unit,
    Positional(Vec<String>),
    Named(Vec<NamedField<'a>>),
}

impl Payload<'_> {
    /// Produces stable local names for the compact slots in a handwritten variant codec.
    fn bindings(&self) -> Vec<String> {
        let count = match self {
            Self::Unit => 0,
            Self::Positional(fields) => fields.len(),
            Self::Named(fields) => fields.len(),
        };
        (0..count).map(|index| format!("field_{index}")).collect()
    }
}

impl RustVariant<'_> {
    /// Writes an enum variant and its named or positional public payload.
    fn write(&self, output: &mut String, derived: bool) {
        let Self {
            public,
            identifier,
            payload,
        } = self;
        writeln!(
            output,
            "    #[doc = {:?}]",
            format!("Game variant {public:?}.")
        )
        .unwrap();
        if derived {
            writeln!(output, "    #[serde(rename = {public:?})]").unwrap();
        }
        match payload {
            Payload::Unit => writeln!(output, "    {identifier},").unwrap(),
            Payload::Positional(types) => {
                writeln!(output, "    {identifier}({}),", types.join(", ")).unwrap()
            }
            Payload::Named(fields) => {
                writeln!(output, "    {identifier} {{").unwrap();
                for field in fields {
                    field.write(output, "        ", "", derived);
                }
                output.push_str("    },\n");
            }
        }
    }

    /// Builds a matching binding pattern or construction expression from compact slot positions.
    fn pattern(&self, slots: &[String]) -> String {
        let name = &self.identifier;
        match &self.payload {
            Payload::Unit => format!("Self::{name}"),
            Payload::Positional(_) => format!("Self::{name}({})", slots.join(", ")),
            Payload::Named(fields) => {
                let assignments = fields
                    .iter()
                    .zip(slots)
                    .map(|(field, slot)| format!("{}: {slot}", field.identifier))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("Self::{name} {{ {assignments} }}")
            }
        }
    }
}

/// Converts snake-case and kebab-case enum tags to conventional Rust variant names.
fn variant_identifier(name: &str) -> String {
    let mut identifier = String::new();
    for word in name.split(['_', '-']).filter(|word| !word.is_empty()) {
        let mut chars = word.chars();
        identifier.push(chars.next().expect("nonempty word").to_ascii_uppercase());
        identifier.extend(chars);
    }
    identifier
}

/// Reserves an identifier or assigns a stable fallback for unusual or duplicate spellings.
fn unique_identifier(preferred: &str, fallback: &str, used: &mut HashSet<String>) -> String {
    let mut bytes = preferred.bytes();
    let valid = bytes
        .next()
        .is_some_and(|byte| byte.is_ascii_alphabetic() || byte == b'_')
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
        && !matches!(preferred, "_" | "crate" | "self" | "Self" | "super");
    let mut name = if valid && used.insert(preferred.to_owned()) {
        preferred.to_owned()
    } else {
        let mut candidate = fallback.to_owned();
        while !used.insert(candidate.clone()) {
            candidate.push('_');
        }
        candidate
    };
    if matches!(
        name.as_str(),
        "as" | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "static"
            | "struct"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "abstract"
            | "become"
            | "box"
            | "do"
            | "final"
            | "gen"
            | "macro"
            | "override"
            | "priv"
            | "try"
            | "typeof"
            | "unsized"
            | "virtual"
            | "yield"
    ) {
        name.insert_str(0, "r#");
    }
    name
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Refreshes generated types without replacing editable source or writing identical content.
    #[test]
    fn regenerates_only_the_owned_binding_module() -> Result<()> {
        let project = tempfile::tempdir()?;
        let src = project.path().join("src");
        fs::create_dir(&src)?;
        let policy = src.join("lib.rs");
        fs::write(&policy, "editable policy")?;
        let game = src.join("game.rs");
        let schema = GameSchema::new(
            Schema::Null,
            Schema::Dynamic,
            Schema::String,
            Schema::Bool,
            Schema::U64,
            Schema::Null,
        );
        bindings(&game, &schema)?;
        let first = fs::read_to_string(&game)?;
        assert!(first.contains("pub type Action = serde_json::Value;"));
        assert!(first.contains("pub type ViewA = String;"));
        assert!(first.contains("pub type ViewB = bool;"));
        assert!(first.contains("pub type Completion = u64;"));
        let modified = fs::metadata(&game)?.modified()?;
        bindings(&game, &schema)?;
        assert_eq!(fs::metadata(&game)?.modified()?, modified);

        let schema = GameSchema {
            view_b: schema.view_a.clone(),
            ..schema
        };
        bindings(&game, &schema)?;
        assert!(fs::read_to_string(&game)?.contains("pub type ViewB = ViewA;"));
        assert_eq!(fs::read_to_string(&policy)?, "editable policy");

        fs::write(&game, "// Handwritten bindings\n")?;
        assert!(bindings(&game, &schema).is_err());
        assert_eq!(fs::read_to_string(&game)?, "// Handwritten bindings\n");
        Ok(())
    }
}
